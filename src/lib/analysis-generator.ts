function getCultureContext(work: Work): CultureContext {
  const country = work.country;
  if (country.includes("中国") || country.includes("China")) return cultureDB.china;
  if (country.includes("日本") || country.includes("Japan")) return cultureDB.japan;
  if (country.includes("印度") || country.includes("India")) return cultureDB.india;
  if (country.includes("波斯") || country.includes("伊朗") || country.includes("Iran") || country.includes("Persia")) return cultureDB.persia;
  if (country.includes("俄") || country.includes("Russia")) return cultureDB.russia;
  if (country.includes("美") || country.includes("USA") || country.includes("美国")) return cultureDB.usa;
  if (["哥伦比亚", "阿根廷", "秘鲁", "智利", "墨西哥", "巴西"].some(c => country.includes(c))) return cultureDB.latinAmerica;
  if (["尼日利亚", "肯尼亚", "南非", "塞内加尔", "加纳", "埃及", "苏丹", "津巴布韦", "喀麦隆"].some(c => country.includes(c))) return cultureDB.africa;
  if (["澳大利亚", "新西兰"].some(c => country.includes(c))) return cultureDB.oceania;
  return cultureDB.westEurope;
}

